// Package dataexport 实现从故障中恢复、并保证一致快照语义的用户数据导出服务。
//
// # 一致性模型
//
// 创建任务时固定快照水位（watermark）与待生成分片集合；外部请求号（RequestID）
// 与导出范围（Scope）共同决定幂等结果，同号改变范围报 request_conflict。
// 工作者凭带到期时间的租约领取分片，租约代际单调递增；上传后的摘要回执必须同时
// 匹配任务当前执行版本与分片当前租约，且对象服务端摘要等于创建时固定的期望摘要。
// 重放同一回执返回原结果；旧租约、错误版本或摘要不一致的回执不能覆盖已接受内容。
//
// 仅当所有分片都属于同一快照水位且摘要校验通过，系统才在一个事务内一次性生成
// 不可变清单、置任务完成并写入一条 task.completed outbox 通知；并发完成最后分片、
// 取消、过期互相竞争时，由可串行化事务保证唯一终态。取消后停止新领取并递增执行
// 版本；超过处理截止的任务由过期扫描终结；清单超过保留期后下载被拒绝，清理过程
// 不删除任何仍被有效清单引用的对象。
